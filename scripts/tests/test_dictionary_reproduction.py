import importlib.util
from pathlib import Path
import tempfile
import unittest

spec=importlib.util.spec_from_file_location('dictionary_reproduction', Path(__file__).parents[1]/'verify_dictionary_reproduction.py')
module=importlib.util.module_from_spec(spec);spec.loader.exec_module(module)


class ReproductionComparisonTest(unittest.TestCase):
    def test_changed_or_missing_sidecar_cannot_pass_by_dictionary_hash_alone(self):
        with tempfile.TemporaryDirectory() as folder:
            left,right=Path(folder)/'left',Path(folder)/'right'
            left.mkdir();right.mkdir()
            for name in module.FILES:
                (left/name).write_text('same',encoding='utf-8')
                (right/name).write_text('same',encoding='utf-8')
            self.assertEqual([],module.compare(left,right))
            (right/'candidate-reviewed.json').write_text('changed',encoding='utf-8')
            self.assertEqual(['candidate-reviewed.json: regenerated bytes differ'],module.compare(left,right))
            (right/'candidate-reviewed.json').unlink()
            self.assertEqual(['candidate-reviewed.json: missing resource'],module.compare(left,right))
