"""Verify that the public editorial source regenerates every shipped runtime index."""
import argparse
import hashlib
from pathlib import Path
import subprocess
import sys
import tempfile

FILES = ('candidate.json', 'candidate.manifest.json', 'candidate-matching.json',
         'candidate-reviewed.json', 'candidate-scoped-descriptions.json')


def compare(expected: Path, actual: Path) -> list[str]:
    differences = []
    for name in FILES:
        left, right = expected / name, actual / name
        if not left.is_file() or not right.is_file():
            differences.append(name + ': missing resource')
        elif hashlib.sha256(left.read_bytes()).digest() != hashlib.sha256(right.read_bytes()).digest():
            differences.append(name + ': regenerated bytes differ')
    return differences


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[1])
    args = parser.parse_args(); root = args.root.resolve()
    with tempfile.TemporaryDirectory(prefix='skyblock-dictionary-reproduction-') as folder:
        output = Path(folder)
        subprocess.run([sys.executable, str(root/'scripts/compile_dictionary.py'),
                        '--source-snapshot', str(root/'dictionary-source/snapshot.zip'), '--candidate',
                        '--output', str(output/'candidate.json'), '--report', str(output/'candidate.manifest.json')], check=True)
        errors = compare(root/'src/main/resources/assets/skyblock_jp/dictionary', output)
        if errors:
            print('\n'.join(errors), file=sys.stderr); return 1
    print('Public source reproduced all five runtime resources byte for byte')
    return 0


if __name__ == '__main__': raise SystemExit(main())
